# Generates the Object overloads for 1..16 fields:
#   src/DataCodec/Codecs/Codec.Object.cs          Codec.Object<TOwner, T1..Tn>(...)
#   src/DataCodec/Codecs/ObjectBuilder.Object.cs  Codec.For<TBase>().Object<TSub, T1..Tn>(...)
# Run from anywhere: pwsh tools/GenerateObjectOverloads.ps1 (Windows PowerShell 5.1 works too).
# Output is LF-terminated UTF-8 without a BOM, so re-running it on unchanged input is a no-op.

$ErrorActionPreference = 'Stop'
$MaxFields = 16
$Root = Split-Path -Parent $PSScriptRoot
$CodecsDir = Join-Path $Root 'src/DataCodec/Codecs'

function Join-Range([int]$count, [scriptblock]$item, [string]$separator = ', ') {
    (1..$count | ForEach-Object { & $item $_ }) -join $separator
}

function Write-Generated([string]$path, [string[]]$lines) {
    $text = ($lines -join "`n") + "`n"
    [System.IO.File]::WriteAllText($path, $text, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "wrote $path"
}

$header = '// <auto-generated> by tools/GenerateObjectOverloads.ps1 - do not edit by hand.'

# ---- Codec.Object.cs ------------------------------------------------------------------------------------------

$lines = @(
    $header
    'using DataCodec.Codecs.Internal;'
    ''
    'namespace DataCodec.Codecs;'
    ''
    'public static partial class Codec'
    '{'
)

for ($n = 1; $n -le $MaxFields; $n++) {
    $typeParams = Join-Range $n { param($i) "T$i" }
    $fields = Join-Range $n { param($i) "FieldCodec<TOwner, T$i> f$i" }
    $constraints = Join-Range $n { param($i) "where T$i : notnull" } ' '
    $fieldList = Join-Range $n { param($i) "f$i" }
    $casts = Join-Range $n { param($i) "(T$i)v[$($i - 1)]" }

    if ($n -gt 1) { $lines += '' }
    $lines += @(
        "    /// <summary>An object codec with $n field(s); <paramref name=`"supplier`"/> builds the value from the decoded fields, in order.</summary>"
        '    /// <exception cref="ArgumentException">Two fields have the same key.</exception>'
        "    public static IMapCodec<TOwner> Object<TOwner, $typeParams>("
        "        $fields,"
        "        Func<$typeParams, TOwner> supplier)"
        "        where TOwner : notnull $constraints"
        '    {'
        '        ArgumentNullException.ThrowIfNull(supplier);'
        "        return new ObjectCodec<TOwner>([$fieldList], v => supplier($casts));"
        '    }'
    )
}

$lines += '}'
Write-Generated (Join-Path $CodecsDir 'Codec.Object.cs') $lines

# ---- ObjectBuilder.Object.cs ----------------------------------------------------------------------------------

$lines = @(
    $header
    'namespace DataCodec.Codecs;'
    ''
    'public readonly partial struct ObjectBuilder<TBase>'
    '{'
)

for ($n = 1; $n -le $MaxFields; $n++) {
    $typeParams = Join-Range $n { param($i) "T$i" }
    $fields = Join-Range $n { param($i) "FieldCodec<TSub, T$i> f$i" }
    $constraints = Join-Range $n { param($i) "where T$i : notnull" } ' '
    $fieldList = Join-Range $n { param($i) "f$i" }

    if ($n -gt 1) { $lines += '' }
    $lines += @(
        "    /// <summary>A codec with $n field(s) for the subtype <typeparamref name=`"TSub`"/>, used as a codec for <typeparamref name=`"TBase`"/>; <paramref name=`"supplier`"/> builds the value from the decoded fields, in order.</summary>"
        '    /// <exception cref="ArgumentException">Two fields have the same key.</exception>'
        "    public IMapCodec<TBase> Object<TSub, $typeParams>("
        "        $fields,"
        "        Func<$typeParams, TSub> supplier)"
        "        where TSub : notnull, TBase $constraints =>"
        "        Codec.Object($fieldList, supplier).Upcast<TSub, TBase>();"
    )
}

$lines += '}'
Write-Generated (Join-Path $CodecsDir 'ObjectBuilder.Object.cs') $lines
